#[test]
fn testGeneratesForeignKeySqlForNonStandardOptions() {
    let platform = platform();
    for (options, expected) in [
        (php_array!["onDelete" => "CASCADE"], " ON DELETE CASCADE"),
        (php_array!["match" => "full"], " MATCH full"),
        (php_array!["deferrable" => true], " DEFERRABLE"),
        (php_array!["deferred" => true], " INITIALLY DEFERRED"),
        (php_array!["deferred" => true], " INITIALLY DEFERRED"),
        (
            php_array!["deferrable" => true, "deferred" => true, "match" => "full"],
            " MATCH full DEFERRABLE INITIALLY DEFERRED",
        ),
    ] {
        let foreign_key =
            ForeignKeyConstraint::new(["foreign_id"], "my_table", ["id"], "my_fk", options)
                .unwrap();
        assert_eq!(
            platform
                .get_foreign_key_declaration_sql(&foreign_key)
                .unwrap(),
            format!("CONSTRAINT my_fk FOREIGN KEY (foreign_id) REFERENCES my_table (id){expected}")
        );
    }
}

