/// `Column::editor()->setUnquotedName($name)->setTypeName($type)`, with
/// `setFixed()` / `setLength()`.
fn binary(name: &str, type_name: &str, fixed: bool, length: Option<i64>) -> Column {
    let mut editor = column(name, type_name);
    if fixed {
        editor = editor.set_fixed(true);
    }
    if length.is_some() {
        editor = editor.set_length(length);
    }
    editor.create().unwrap()
}

fn mytable(columns: Vec<Column>) -> Table {
    Table::editor()
        .set_unquoted_name("mytable", None)
        .set_columns(columns)
        .create()
        .unwrap()
}

#[test]
fn testDoesNotPropagateUnnecessaryTableAlterationOnBinaryType() {
    let platform = platform();
    let table1 = mytable(vec![
        binary("column_varbinary", Types::BINARY, false, None),
        binary("column_binary", Types::BINARY, true, None),
        binary("column_blob", Types::BLOB, false, None),
    ]);

    let table2 = mytable(vec![
        binary("column_varbinary", Types::BINARY, true, None),
        binary("column_binary", Types::BINARY, false, None),
        binary("column_blob", Types::BINARY, false, None),
    ]);

    let comparator = create_comparator(&platform);

    // VARBINARY -> BINARY
    // BINARY    -> VARBINARY
    // BLOB      -> VARBINARY
    assert!(
        comparator
            .compare_tables(&table1, &table2)
            .unwrap()
            .is_empty()
    );

    let table2 = mytable(vec![
        binary("column_varbinary", Types::BINARY, false, Some(42)),
        binary("column_binary", Types::BLOB, false, None),
        binary("column_blob", Types::BINARY, true, Some(11)),
    ]);

    // VARBINARY -> VARBINARY with changed length
    // BINARY    -> BLOB
    // BLOB      -> BINARY
    assert!(
        comparator
            .compare_tables(&table1, &table2)
            .unwrap()
            .is_empty()
    );

    let table2 = mytable(vec![
        binary("column_varbinary", Types::BLOB, false, None),
        binary("column_binary", Types::BINARY, true, Some(42)),
        binary("column_blob", Types::BLOB, false, None),
    ]);

    // VARBINARY -> BLOB
    // BINARY    -> BINARY with changed length
    // BLOB      -> BLOB
    assert!(
        comparator
            .compare_tables(&table1, &table2)
            .unwrap()
            .is_empty()
    );
}

