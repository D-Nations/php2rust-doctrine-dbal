#[tokio::test]
async fn testListSameTableNameColumnsWithDifferentSchema() {
    let Some(connection) =
        pgsql_support::pgsql("testListSameTableNameColumnsWithDifferentSchema").await
    else {
        return;
    };
    let sm = schema_manager(&connection).await;

    exec(&connection, "DROP SCHEMA IF EXISTS another CASCADE").await;
    exec(&connection, "DROP TABLE IF EXISTS \"table\"").await;

    exec(&connection, "CREATE SCHEMA another").await;
    let table = Table::editor()
        .set_unquoted_name("table", None)
        .set_columns(vec![
            column("id", Types::INTEGER).create().unwrap(),
            column("name", Types::TEXT).create().unwrap(),
        ])
        .create()
        .unwrap();

    sm.create_table(&table).await.unwrap();

    let another_schema_table = Table::editor()
        .set_unquoted_name("table", Some("another"))
        .set_columns(vec![
            column("id", Types::TEXT).create().unwrap(),
            column("email", Types::TEXT).create().unwrap(),
        ])
        .create()
        .unwrap();

    sm.create_table(&another_schema_table).await.unwrap();

    let table = sm
        .introspect_table_by_unquoted_name("table", None)
        .await
        .unwrap();
    assert_eq!(2, table.get_columns().len());
    assert!(table.has_column("id"));
    assert_eq!(Types::INTEGER, type_name(table.get_column("id").unwrap()));
    assert!(table.has_column("name"));

    let another_schema_table = sm
        .introspect_table_by_unquoted_name("table", Some("another"))
        .await
        .unwrap();
    assert_eq!(2, another_schema_table.get_columns().len());
    assert!(another_schema_table.has_column("id"));
    assert_eq!(
        Types::TEXT,
        type_name(another_schema_table.get_column("id").unwrap())
    );
    assert!(another_schema_table.has_column("email"));
}

#[tokio::test]
async fn testReturnQuotedAssets() {
    let Some(connection) = pgsql_support::pgsql("testReturnQuotedAssets").await else {
        return;
    };
    let sm = schema_manager(&connection).await;

    exec(&connection, "DROP TABLE IF EXISTS dbal91_something").await;

    let sql = "create table dbal91_something \
               (id integer CONSTRAINT id_something PRIMARY KEY NOT NULL, \"table\" integer)";
    exec(&connection, sql).await;

    let sql = "ALTER TABLE dbal91_something ADD CONSTRAINT something_input \
               FOREIGN KEY( \"table\" ) REFERENCES dbal91_something ON UPDATE CASCADE;";
    exec(&connection, sql).await;

    let table = sm.introspect_table("dbal91_something").await.unwrap();

    assert_eq!(
        vec![
            "CREATE TABLE dbal91_something (id INT NOT NULL, \"table\" INT DEFAULT NULL, PRIMARY KEY (id))",
            "CREATE INDEX IDX_A9401304ECA7352B ON dbal91_something (\"table\")",
            "ALTER TABLE dbal91_something ADD CONSTRAINT something_input FOREIGN KEY (\"table\") \
             REFERENCES dbal91_something (id) ON UPDATE CASCADE NOT DEFERRABLE INITIALLY IMMEDIATE",
        ],
        platform(&connection)
            .await
            .get_create_table_sql(&table)
            .unwrap()
    );
}

