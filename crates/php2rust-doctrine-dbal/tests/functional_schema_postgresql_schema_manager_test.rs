#[tokio::test]
async fn testPartialIndexes() {
    let Some(connection) = pgsql_support::pgsql("testPartialIndexes").await else {
        return;
    };
    let sm = schema_manager(&connection).await;

    let offline_table = Table::editor()
        .set_unquoted_name("person", None)
        .set_columns(vec![
            column("id", Types::INTEGER).create().unwrap(),
            column("name", Types::STRING).create().unwrap(),
            column("email", Types::STRING).create().unwrap(),
        ])
        .set_indexes(vec![
            Index::editor()
                .set_unquoted_name("simple_partial_index")
                .set_type(IndexType::Unique)
                .set_unquoted_column_names(&["id", "name"])
                .set_predicate(Some("(id IS NULL)"))
                .create()
                .unwrap(),
        ])
        .create()
        .unwrap();

    drop_and_create_table(&connection, &offline_table).await;

    let online_table = sm
        .introspect_table_by_unquoted_name("person", None)
        .await
        .unwrap();

    assert!(
        sm.create_comparator()
            .await
            .unwrap()
            .compare_tables(&online_table, &offline_table)
            .unwrap()
            .is_empty()
    );
    assert!(online_table.has_index("simple_partial_index"));
    let index = online_table.get_index("simple_partial_index").unwrap();
    assert!(index.has_option("where"));
    assert!(
        index
            .get_option("where")
            .is_some_and(|w| w.identical(&Value::string("(id IS NULL)")))
    );
}

#[tokio::test]
async fn testJsonbColumn() {
    let Some(connection) = pgsql_support::pgsql("testJsonbColumn").await else {
        return;
    };
    let sm = schema_manager(&connection).await;

    let mut foo = column("foo", Types::JSON).create().unwrap();
    foo.set_platform_option("jsonb", Value::Bool(true));
    let table = Table::editor()
        .set_unquoted_name("test_jsonb", None)
        .set_columns(vec![foo])
        .create()
        .unwrap();

    drop_and_create_table(&connection, &table).await;

    let columns = sm.list_table_columns("test_jsonb").await.unwrap();
    let foo = columns.get("foo").unwrap();

    assert_eq!(Types::JSON, type_name(foo));
    assert!(
        foo.get_platform_option("jsonb")
            .is_some_and(|v| v.identical(&Value::Bool(true)))
    );
}
