#[tokio::test]
async fn testAlterTableAutoIncrementAdd() {
    let Some(connection) = pgsql_support::pgsql("testAlterTableAutoIncrementAdd").await else {
        return;
    };
    let sm = schema_manager(&connection).await;

    let table_from = Table::editor()
        .set_unquoted_name("autoinc_table_add", None)
        .set_columns(vec![column("id", Types::INTEGER).create().unwrap()])
        .create()
        .unwrap();

    drop_and_create_table(&connection, &table_from).await;
    let table_from = sm
        .introspect_table_by_unquoted_name("autoinc_table_add", None)
        .await
        .unwrap();
    assert!(!table_from.get_column("id").unwrap().get_autoincrement());

    let table_to = Table::editor()
        .set_unquoted_name("autoinc_table_add", None)
        .set_columns(vec![
            column("id", Types::INTEGER)
                .set_autoincrement(true)
                .create()
                .unwrap(),
        ])
        .create()
        .unwrap();

    let platform = platform(&connection).await;
    let diff = sm
        .create_comparator()
        .await
        .unwrap()
        .compare_tables(&table_from, &table_to)
        .unwrap();

    let sql = platform.get_alter_table_sql(&diff).unwrap();
    assert_eq!(
        vec!["ALTER TABLE autoinc_table_add ALTER id ADD GENERATED BY DEFAULT AS IDENTITY"],
        sql
    );

    sm.alter_table(&diff).await.unwrap();
    let table_final = sm
        .introspect_table_by_unquoted_name("autoinc_table_add", None)
        .await
        .unwrap();
    assert!(table_final.get_column("id").unwrap().get_autoincrement());
}

