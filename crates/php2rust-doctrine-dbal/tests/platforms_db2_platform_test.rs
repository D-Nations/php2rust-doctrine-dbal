/// The columns of `getGeneratesAlterColumnSQL()`, in its order.
fn generates_alter_column_sql_columns() -> Vec<(Column, Column)> {
    let bar = |type_name: &str| column("bar", type_name);
    let create = |editor: php2rust_doctrine_dbal::schema::ColumnEditor| editor.create().unwrap();

    vec![
        (
            create(bar(Types::DECIMAL).set_column_definition(Some("MONEY NULL"))),
            create(bar(Types::DECIMAL).set_column_definition(Some("MONEY NOT NULL"))),
        ),
        (create(bar(Types::STRING)), create(bar(Types::INTEGER))),
        (
            create(bar(Types::STRING).set_length(Some(50))),
            create(bar(Types::STRING).set_length(Some(100))),
        ),
        (
            create(bar(Types::DECIMAL).set_precision(Some(8)).set_scale(2)),
            create(bar(Types::DECIMAL).set_precision(Some(10)).set_scale(2)),
        ),
        (
            create(bar(Types::DECIMAL).set_precision(Some(5)).set_scale(3)),
            create(bar(Types::DECIMAL).set_precision(Some(5)).set_scale(4)),
        ),
        (
            create(bar(Types::STRING).set_length(Some(10)).set_fixed(true)),
            create(bar(Types::STRING).set_length(Some(20)).set_fixed(true)),
        ),
        (
            create(bar(Types::STRING).set_not_null(false)),
            create(bar(Types::STRING)),
        ),
        (
            create(bar(Types::STRING)),
            create(bar(Types::STRING).set_not_null(false)),
        ),
        (
            create(bar(Types::STRING)),
            create(bar(Types::STRING).set_default_value(Value::from("foo"))),
        ),
        (
            create(bar(Types::INTEGER)),
            create(
                bar(Types::INTEGER)
                    .set_autoincrement(true)
                    .set_default_value(Value::Int(666)),
            ),
        ),
        (
            create(bar(Types::STRING).set_default_value(Value::from("foo"))),
            create(bar(Types::STRING)),
        ),
    ]
}

#[test]
fn testGeneratesAlterColumnSQL() {
    let recorded = rows::<Case>("testGeneratesAlterColumnSQL");
    let columns = generates_alter_column_sql_columns();
    assert_eq!(recorded.len(), columns.len());

    for ((name, args), (old_column, new_column)) in recorded.into_iter().zip(columns) {
        let expected_sql_clause = match args[2][0].as_str() {
            Some("null") => None,
            _ => Some(text(&args[2])),
        };
        let should_reorg = args.get(3).is_none_or(|flag| flag[1] == true);

        let table = Table::editor()
            .set_unquoted_name("foo", None)
            .set_columns(vec![column("id", Types::INTEGER).create().unwrap()])
            .create()
            .unwrap();

        let table_diff = TableDiff::new(
            table,
            TableDiffParts {
                changed_columns: vec![ColumnDiff::new(old_column, new_column)],
                ..TableDiffParts::default()
            },
        );

        let mut expected_sql = Vec::new();

        if let Some(expected_sql_clause) = expected_sql_clause {
            expected_sql.push(format!(
                "ALTER TABLE foo ALTER COLUMN bar {expected_sql_clause}"
            ));
        }

        if should_reorg {
            expected_sql.push("CALL SYSPROC.ADMIN_CMD ('REORG TABLE foo')".to_owned());
        }

        assert_eq!(
            platform().get_alter_table_sql(&table_diff).unwrap(),
            expected_sql,
            "{name}"
        );
    }
}
